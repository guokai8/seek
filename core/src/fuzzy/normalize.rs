/// Folds a Latin-script character down to its base ASCII letter.
///
/// Returns `None` when the character has no ASCII base form, in which case
/// the caller should keep the original character.
pub fn normalize_char(c: char) -> Option<char> {
    let code = c as u32;
    if code < 0x00C0 {
        return None;
    }
    // Binary search over the runs.
    let mut lo = 0usize;
    let mut hi = RUNS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (start, end, base) = RUNS[mid];
        if code < start {
            hi = mid;
        } else if code > end {
            lo = mid + 1;
        } else {
            let offset = (code - start) as u8;
            return Some((base as u8 + offset) as char);
        }
    }
    None
}
